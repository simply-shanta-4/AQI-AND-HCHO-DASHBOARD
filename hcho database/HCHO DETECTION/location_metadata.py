def get_location_name(cid, format="standard"):
    """
    Returns formatted location name for a given cluster_id.
    format options:
    - 'standard': e.g. "Sangli-Satara Sugar Belt"
    - 'full': e.g. "Sangli-Satara Sugar & Agro Belt (MH)"
    - 'short': e.g. "Sangli-Satara (MH)"
    """
    try:
        cid = int(cid)
    except (ValueError, TypeError):
        return str(cid)
        
    info = CLUSTER_LOCATIONS.get(cid, None)
    if info is None:
        return f"Cluster {cid}"
    if format == "full":
        return info["full_name"]
    elif format == "short":
        return info["short_name"]
    return info["location_name"]


